-- CompanyVault follow-up: adds a first-class Company entity and a per-(company, question) rank/
-- frequency join table. Neither replaces canonical_question_company (the existing tag-based
-- company list on CanonicalQuestion) - both are additive. See:
--   com.placement.questionbank.entity.Company
--   com.placement.questionbank.entity.CompanyQuestionRank
--   com.placement.questionbank.service.CompanyVaultSeedService

CREATE TABLE public.company (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    slug character varying(150) NOT NULL,
    name character varying(200) NOT NULL,
    total_distinct_available integer,
    included_in_sheet integer,
    capped boolean,
    created_at timestamp(6) with time zone NOT NULL,
    updated_at timestamp(6) with time zone,
    CONSTRAINT uk_company_slug UNIQUE (slug)
);

CREATE TABLE public.company_question_rank (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    company_id bigint NOT NULL,
    canonical_question_id bigint NOT NULL,
    rank integer,
    frequency_score double precision,
    created_at timestamp(6) with time zone NOT NULL,
    updated_at timestamp(6) with time zone,
    CONSTRAINT uk_company_question UNIQUE (company_id, canonical_question_id),
    CONSTRAINT fk_company_question_rank_company
        FOREIGN KEY (company_id) REFERENCES public.company (id),
    CONSTRAINT fk_company_question_rank_canonical_question
        FOREIGN KEY (canonical_question_id) REFERENCES public.canonical_question (id)
);

CREATE INDEX idx_company_question_rank_company ON public.company_question_rank (company_id);
CREATE INDEX idx_company_question_rank_question ON public.company_question_rank (canonical_question_id);
