-- V22: Interview Reports and Terminal Statuses
-- 1. Update interview_session status check constraint to include all terminal states (VIOLATION_DETECTED, TIMEOUT, ADMIN_TERMINATED)
ALTER TABLE public.interview_session DROP CONSTRAINT IF EXISTS interview_session_status_check;
ALTER TABLE public.interview_session ADD CONSTRAINT interview_session_status_check CHECK (
    (status)::text = ANY (ARRAY[
        'CREATED'::character varying,
        'READY'::character varying,
        'IN_PROGRESS'::character varying,
        'PAUSED'::character varying,
        'EXITED'::character varying,
        'RESUMABLE'::character varying,
        'COMPLETED'::character varying,
        'SUBMITTED'::character varying,
        'REPORT_GENERATING'::character varying,
        'REPORT_READY'::character varying,
        'CANCELLED'::character varying,
        'TERMINATED_VIOLATION'::character varying,
        'VIOLATION_DETECTED'::character varying,
        'TIMEOUT'::character varying,
        'ADMIN_TERMINATED'::character varying
    ]::text[])
);

-- 2. Create interview_report table
CREATE TABLE IF NOT EXISTS public.interview_report (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    interview_session_id BIGINT NOT NULL,
    student_id BIGINT NOT NULL,
    status CHARACTER VARYING(50) NOT NULL DEFAULT 'PENDING',
    terminal_status CHARACTER VARYING(50),
    exit_reason CHARACTER VARYING(500),
    technical_score DOUBLE PRECISION,
    behavioral_score DOUBLE PRECISION,
    confidence_score DOUBLE PRECISION,
    overall_score DOUBLE PRECISION,
    coding_score DOUBLE PRECISION,
    integrity_score DOUBLE PRECISION,
    violation_count INTEGER DEFAULT 0,
    failure_reason TEXT,
    report_data TEXT,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP NOT NULL,
    updated_at TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CONSTRAINT uk_interview_report_session UNIQUE (interview_session_id),
    CONSTRAINT fk_interview_report_session FOREIGN KEY (interview_session_id) REFERENCES public.interview_session(id) ON DELETE CASCADE,
    CONSTRAINT fk_interview_report_student FOREIGN KEY (student_id) REFERENCES public.app_user(id) ON DELETE CASCADE,
    CONSTRAINT chk_interview_report_status CHECK (
        (status)::text = ANY (ARRAY[
            'PENDING'::character varying,
            'GENERATING'::character varying,
            'GENERATED'::character varying,
            'FAILED'::character varying
        ]::text[])
    )
);

CREATE INDEX IF NOT EXISTS idx_interview_report_student_id ON public.interview_report(student_id);
CREATE INDEX IF NOT EXISTS idx_interview_report_status ON public.interview_report(status);
