-- No audit-log table existed anywhere in this codebase before this migration - every admin
-- mutation (question CRUD, access grants/revokes, test publish, etc.) had no audit trail at all.
-- This is deliberately generic (actor/action/entity/details) rather than one table per feature,
-- so every admin action this session and future ones can write to the same log via AuditLogService
-- instead of each feature inventing its own audit mechanism (see spec section 83, "no duplicate
-- systems" - this applies to audit logging just as much as to entities and controllers).

CREATE TABLE public.audit_log (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    admin_id      BIGINT REFERENCES public.app_user (id),
    admin_name    VARCHAR(255),
    action        VARCHAR(100) NOT NULL,
    entity_type   VARCHAR(100),
    entity_id     BIGINT,
    details       VARCHAR(2000),
    created_at    TIMESTAMP(6) WITH TIME ZONE NOT NULL DEFAULT now()
);

CREATE INDEX idx_audit_log_entity ON public.audit_log (entity_type, entity_id);
CREATE INDEX idx_audit_log_admin ON public.audit_log (admin_id);
CREATE INDEX idx_audit_log_created_at ON public.audit_log (created_at);
