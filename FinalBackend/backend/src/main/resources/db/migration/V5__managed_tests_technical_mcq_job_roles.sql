-- =====================================================================================
-- V5: Admin Assessment / Test Management module
--
--   1. technical_mcq_question (+ company/tag element collections)  - Question Bank extension
--   2. managed_test / _section / _question / _assignment / _attempt / _answer - the test engine
--   3. job_role                                                     - additive columns only
--   4. integrity_event.attempt_kind                                 - discriminator + backfill
--
-- Everything is additive. No existing table is dropped, no existing column changes type, and no
-- existing CHECK constraint is rewritten, so this migration is safe to run against a live database
-- with attempts already in it.
--
-- Column names follow Hibernate's default snake_case strategy so `ddl-auto: validate` passes.
-- =====================================================================================


-- -------------------------------------------------------------------------------------
-- 1. Technical MCQ question bank
-- -------------------------------------------------------------------------------------

CREATE TABLE public.technical_mcq_question (
    id                       bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    question_text            text NOT NULL,
    category                 varchar(40) NOT NULL,
    topic                    varchar(120),
    subtopic                 varchar(120),
    difficulty               varchar(20),
    options                  jsonb NOT NULL DEFAULT '[]'::jsonb,
    correct_options          jsonb NOT NULL DEFAULT '[]'::jsonb,
    multiple_correct         boolean NOT NULL DEFAULT false,
    explanation              text,
    default_marks            double precision NOT NULL DEFAULT 1,
    default_negative_marks   double precision NOT NULL DEFAULT 0,
    estimated_time_seconds   integer NOT NULL DEFAULT 60,
    source_ref               varchar(200),
    canonical_question_id    bigint,
    active                   boolean NOT NULL DEFAULT true,
    created_at               timestamp(6) with time zone NOT NULL,
    updated_at               timestamp(6) with time zone,
    CONSTRAINT technical_mcq_question_category_check CHECK (category IN (
        'DSA','ALGORITHMS','OOPS','JAVA','PYTHON','C','CPP','DBMS','SQL','COMPUTER_NETWORKS',
        'OPERATING_SYSTEMS','CLOUD_COMPUTING','AWS','AZURE','GCP','AI','MACHINE_LEARNING',
        'DEEP_LEARNING','GENERATIVE_AI','DATA_SCIENCE','DATA_STRUCTURES','SYSTEM_DESIGN',
        'SOFTWARE_ENGINEERING','COMPUTER_ARCHITECTURE','LINUX','DEVOPS','DOCKER','KUBERNETES',
        'GIT_GITHUB','SPRING_BOOT','REST_API','MICROSERVICES','APTITUDE','LOGICAL_REASONING',
        'QUANTITATIVE_APTITUDE','VERBAL_ABILITY')),
    CONSTRAINT technical_mcq_question_difficulty_check CHECK (difficulty IS NULL OR difficulty IN ('EASY','MEDIUM','HARD'))
);

CREATE UNIQUE INDEX uk_tmq_source_ref ON public.technical_mcq_question (source_ref) WHERE source_ref IS NOT NULL;
CREATE INDEX idx_tmq_category   ON public.technical_mcq_question (category);
CREATE INDEX idx_tmq_difficulty ON public.technical_mcq_question (difficulty);
CREATE INDEX idx_tmq_topic      ON public.technical_mcq_question (topic);
CREATE INDEX idx_tmq_active     ON public.technical_mcq_question (active);

CREATE TABLE public.technical_mcq_question_company (
    question_id bigint NOT NULL REFERENCES public.technical_mcq_question (id) ON DELETE CASCADE,
    company     varchar(255)
);
CREATE INDEX idx_tmq_company ON public.technical_mcq_question_company (question_id);

CREATE TABLE public.technical_mcq_question_tag (
    question_id bigint NOT NULL REFERENCES public.technical_mcq_question (id) ON DELETE CASCADE,
    tag         varchar(255)
);
CREATE INDEX idx_tmq_tag ON public.technical_mcq_question_tag (question_id);


