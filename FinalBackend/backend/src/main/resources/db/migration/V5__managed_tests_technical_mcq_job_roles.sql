    target_job_role_id          bigint,
    difficulty                  varchar(20),
    duration_minutes            integer NOT NULL DEFAULT 60,
    total_marks                 double precision NOT NULL DEFAULT 0,
    passing_percentage          double precision NOT NULL DEFAULT 40,
    negative_marking_enabled    boolean NOT NULL DEFAULT false,
    default_negative_marks      double precision NOT NULL DEFAULT 0.25,
    overall_timer_enabled       boolean NOT NULL DEFAULT true,
    section_timers_enabled      boolean NOT NULL DEFAULT false,
    attempt_limit               integer NOT NULL DEFAULT 1,
    shuffle_sections            boolean NOT NULL DEFAULT false,
    show_result_to_student      boolean NOT NULL DEFAULT true,
    starts_at                   timestamp(6) with time zone,
    ends_at                     timestamp(6) with time zone,
    status                      varchar(20) NOT NULL DEFAULT 'DRAFT',
    proctored                   boolean NOT NULL DEFAULT false,
    fullscreen_required         boolean NOT NULL DEFAULT false,
    webcam_required             boolean NOT NULL DEFAULT false,
