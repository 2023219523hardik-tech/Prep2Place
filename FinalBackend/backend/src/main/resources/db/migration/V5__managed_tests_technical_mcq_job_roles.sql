        'STANDARD_MOCK_TEST','UNIVERSITY_TEST','CUSTOM_TEST','TECHNICAL_MCQ_TEST','COMPANY_TEST','PLACEMENT_TEST')),
    CONSTRAINT managed_test_status_check CHECK (status IN (
        'DRAFT','PUBLISHED','SCHEDULED','ACTIVE','COMPLETED','ARCHIVED')),
    CONSTRAINT managed_test_difficulty_check CHECK (difficulty IS NULL OR difficulty IN ('EASY','MEDIUM','HARD')),
