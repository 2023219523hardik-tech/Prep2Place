-- -------------------------------------------------------------------------------------
-- 3. Job role expansion (additive columns only; title/domain/description/required_skills stay)
-- -------------------------------------------------------------------------------------

ALTER TABLE public.job_role ADD COLUMN IF NOT EXISTS department          varchar(120);
ALTER TABLE public.job_role ADD COLUMN IF NOT EXISTS preferred_skills    varchar(1000);
ALTER TABLE public.job_role ADD COLUMN IF NOT EXISTS experience_level    varchar(40);
ALTER TABLE public.job_role ADD COLUMN IF NOT EXISTS min_readiness_score integer;
ALTER TABLE public.job_role ADD COLUMN IF NOT EXISTS active              boolean NOT NULL DEFAULT true;

-- Existing rows predate `department`; mirror the legacy `domain` so neither reader sees a null.
UPDATE public.job_role SET department = domain WHERE department IS NULL;


-- -------------------------------------------------------------------------------------
-- 4. integrity_event: which attempt table attempt_id points at
--
-- The column has no FK (it never did), which is exactly why it can now serve two attempt tables.
-- Every existing row belongs to the legacy engine, so the backfill is a blanket ASSESSMENT.
-- -------------------------------------------------------------------------------------

ALTER TABLE public.integrity_event
    ADD COLUMN IF NOT EXISTS attempt_kind varchar(20) NOT NULL DEFAULT 'ASSESSMENT';

UPDATE public.integrity_event SET attempt_kind = 'ASSESSMENT' WHERE attempt_kind IS NULL;

ALTER TABLE public.integrity_event
    ADD CONSTRAINT integrity_event_attempt_kind_check CHECK (attempt_kind IN ('ASSESSMENT','MANAGED_TEST'));

CREATE INDEX IF NOT EXISTS idx_integrity_event_kind_attempt
    ON public.integrity_event (attempt_kind, attempt_id);
